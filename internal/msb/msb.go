// TranslateNetSpec converts a network profile name ("public", "none", "private",
// "host", "all") or an msb rule token ("allow@...") into flags for 'msb snap restore'.
//
// 'msb snap restore' accepts --no-net, --net-default <allow|deny>, and
// --net-rule <rule>. It does not accept --net <profile>.
func TranslateNetSpec(spec string) ([]string, error) {
	s := strings.TrimSpace(spec)
	switch s {
	case "", "public", "public-only":
		return []string{"--net-default", "deny", "--net-rule", "allow@public"}, nil
	case "none", "deny":
		return []string{"--no-net"}, nil
	case "private":
		return []string{"--net-default", "deny", "--net-rule", "allow@public,allow@private"}, nil
	case "host":
		return []string{"--net-default", "deny", "--net-rule", "allow@public,allow@host"}, nil
	case "all", "allow":
		return []string{"--net-default", "allow"}, nil
	default:
		if strings.Contains(s, "@") {
			return []string{"--net-default", "deny", "--net-rule", s}, nil
		}
		return nil, fmt.Errorf("unsupported --net value %q (use: public, none, private, host, all, or an msb rule like 'allow@example.com:tcp:443')", spec)
	}
}

// ShellQuote wraps s in POSIX single quotes, escaping any embedded single quote
// as `'\”`. The resulting token is safe against all shell expansion (`$`, “ ` “,
// `\`, globbing, and newlines).
func ShellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// FormatEnvExports builds the shell script for GuestKeysFile from non-empty
// environment variables in keys. It uses lookup to read host values and returns
// the script text and the number of exported variables.
func FormatEnvExports(lookup func(string) string, keys []string) (string, int) {
	var b strings.Builder
	b.WriteString("# Auto-generated by agbox. Exists only inside this disposable microVM.\n")
	count := 0
	for _, k := range keys {
		if k == "" {
			continue
		}
		val := lookup(k)
		if val == "" {
			continue
		}
		b.WriteString("export ")
		b.WriteString(k)
		b.WriteByte('=')
		b.WriteString(ShellQuote(val))
		b.WriteByte('\n')
		count++
	}
	return b.String(), count
}

// VolumeSpec describes a single host-to-guest virtiofs mount.
type VolumeSpec struct {
	HostPath  string
	GuestPath string
	ReadOnly  bool
}

// FormatFlag renders the `-v` value with `uid=1000,gid=1000` so the non-root
// guest user can read and write shared files regardless of host file modes.
func (v VolumeSpec) FormatFlag() string {
	mode := "rw"
	if v.ReadOnly {
		mode = "ro"
	}
	return fmt.Sprintf("%s:%s:%s,uid=1000,gid=1000", v.HostPath, v.GuestPath, mode)
}

// CreateOpts holds parameters for `msb create`.
type CreateOpts struct {
	Image    string
	Name     string
	CPUs     string
	Memory   string
	RootDisk string
	Workdir  string
}

// BuildCreateArgs constructs the CLI argument list for `msb create`.
func BuildCreateArgs(opts CreateOpts) ([]string, error) {
	if opts.Image == "" {
		return nil, errors.New("image is required")
	}
	if opts.Name == "" {
		return nil, errors.New("sandbox name is required")
	}
	cpus := opts.CPUs
	if cpus == "" {
		cpus = "4"
	}
	mem := opts.Memory
	if mem == "" {
		mem = "8G"
	}
	args := []string{
		"create", opts.Image,
		"--name", opts.Name,
		"--cpus", cpus,
		"--memory", mem,
	}
	if opts.RootDisk != "" {
		args = append(args, "--root-disk", opts.RootDisk)
	}
	if opts.Workdir != "" {
		args = append(args, "--workdir", opts.Workdir, "--mkdir", opts.Workdir)
	}
	return args, nil
}

// RestoreOpts holds parameters for `msb snap restore`.
type RestoreOpts struct {
	Snapshot string
	Name     string
	User     string
	CPUs     string
	Memory   string
	Volumes  []VolumeSpec
	Ports    []string // e.g. "127.0.0.1:4096:3000"
	NoNet    bool
	NetSpecs []string
}

// BuildRestoreArgs constructs the CLI argument list for `msb snap restore`.
func BuildRestoreArgs(opts RestoreOpts) ([]string, error) {
	if opts.Snapshot == "" {
		return nil, errors.New("snapshot reference is required")
	}
	if opts.Name == "" {
		return nil, errors.New("sandbox name is required")
	}
	user := opts.User
	if user == "" {
		user = GuestUser
	}
	args := []string{
		"snap", "restore", opts.Snapshot,
		"--name", opts.Name,
		"-u", user,
	}
	if opts.CPUs != "" {
		args = append(args, "--cpus", opts.CPUs)
	}
	if opts.Memory != "" {
		args = append(args, "--memory", opts.Memory)
	}
	for _, v := range opts.Volumes {
		args = append(args, "-v", v.FormatFlag())
	}
	for _, p := range opts.Ports {
		args = append(args, "-p", p)
	}
	if opts.NoNet {
		args = append(args, "--no-net")
	} else if len(opts.NetSpecs) > 0 {
		for _, spec := range opts.NetSpecs {
			netFlags, err := TranslateNetSpec(spec)
			if err != nil {
				return nil, err
			}
			args = append(args, netFlags...)
		}
	}
	return args, nil
}

// ExecCmdOpts holds parameters for `msb exec`.
type ExecCmdOpts struct {
	Sandbox  string
	Workdir  string
	User     string
	Detached bool
	TTY      bool
	NoTTY    bool
	Stream   bool
	Env      []string // KEY=VAL pairs
	Command  []string
}

// BuildExecArgs constructs the CLI argument list for `msb exec`.
func BuildExecArgs(opts ExecCmdOpts) []string {
	args := []string{"exec"}
	if opts.Detached {
		args = append(args, "-d")
	}
	if opts.TTY {
		args = append(args, "-t")
	} else if opts.Stream {
		args = append(args, "--stream")
	} else if opts.NoTTY {
		args = append(args, "--no-tty")
	}
	if opts.Workdir != "" {
		args = append(args, "-w", opts.Workdir)
	}
	if opts.User != "" {
		args = append(args, "-u", opts.User)
	}
	for _, kv := range opts.Env {
		args = append(args, "-e", kv)
	}
	args = append(args, opts.Sandbox, "--")
	args = append(args, opts.Command...)
	return args
}

